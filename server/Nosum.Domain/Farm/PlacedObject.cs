using System;

namespace Nosum.Domain.Farm;

/// <summary>
/// One object a player placed on the ground of a map instance (furniture in their farmhouse now). The instance is the map plus its owner
/// (<see cref="MapId"/>, <see cref="OwnerId"/>); the footprint is derived from the item at load time, so the row stores only
/// where and how it stands (docs/adr/ADR-015). Picking the object up deletes the row and returns the item to the inventory in the same transaction.
/// </summary>
public sealed class PlacedObject
{
    /// <summary>Gets or sets the object id, generated by the database and never reused.</summary>
    public int Id { get; set; }

    /// <summary>Gets or sets the map key, for example <c>farmhouse</c>.</summary>
    public string MapId { get; set; } = string.Empty;

    /// <summary>Gets or sets the owner of the instance; <see cref="Guid.Empty"/> for a shared map.</summary>
    public Guid OwnerId { get; set; }

    /// <summary>Gets or sets the inventory item the object is made from.</summary>
    public int ItemId { get; set; }

    /// <summary>Gets or sets the left tile of the footprint.</summary>
    public int TileX { get; set; }

    /// <summary>Gets or sets the top tile of the footprint.</summary>
    public int TileY { get; set; }

    /// <summary>Gets or sets the rotation, zero to three.</summary>
    public int Rotation { get; set; }

    /// <summary>Gets or sets when the object was first placed.</summary>
    public DateTimeOffset PlacedAt { get; set; }

    /// <summary>Gets or sets when the row last changed.</summary>
    public DateTimeOffset UpdatedAt { get; set; }
}
