using System;

namespace Nosum.Domain.Nodes;

/// <summary>
/// One resource node standing on a tile of a map instance: a tree, stump, twig, stone, ore node, weed or tile of grass (docs/adr/ADR-021 D3).
/// The instance is the map plus its owner (<see cref="MapId"/>, <see cref="OwnerId"/>). Hits taken on a node that still stands are kept in
/// memory only; the row changes when the node breaks, grows or is created, so a restart heals a half-chopped tree.
/// </summary>
public sealed class WorldNode
{
    /// <summary>Gets or sets the node id, generated by the database and never reused.</summary>
    public int Id { get; set; }

    /// <summary>Gets or sets the map key, for example <c>forest</c>.</summary>
    public string MapId { get; set; } = string.Empty;

    /// <summary>Gets or sets the owner of the instance; <see cref="Guid.Empty"/> for a shared map.</summary>
    public Guid OwnerId { get; set; }

    /// <summary>Gets or sets the tile x.</summary>
    public int TileX { get; set; }

    /// <summary>Gets or sets the tile y.</summary>
    public int TileY { get; set; }

    /// <summary>Gets or sets the kind (<c>Nosum.Gameplay.Nodes.NodeKind</c>).</summary>
    public short Kind { get; set; }

    /// <summary>Gets or sets the tree species (<c>TreeVariant</c>).</summary>
    public short Variant { get; set; }

    /// <summary>Gets or sets the tree stage (<c>TreeStage</c>).</summary>
    public short Stage { get; set; }

    /// <summary>Gets or sets the hits left when the row was written.</summary>
    public short Hits { get; set; }

    /// <summary>Gets or sets the game days the node has stood.</summary>
    public int AgeDays { get; set; }

    /// <summary>Gets or sets when the node was spawned.</summary>
    public DateTimeOffset SpawnedAt { get; set; }
}
