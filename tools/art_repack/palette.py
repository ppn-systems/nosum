def hexcolor(c):
    return '#%02x%02x%02x' % tuple(c[:3])


def rgba(c):
    return 'rgba(%d, %d, %d, %s)' % (c[0], c[1], c[2], ('%g' % c[3]) if len(c) > 3 else '1')


def contrast(a, b):
    """WCAG contrast ratio of two colours."""
    def lum(c):
        def f(v):
            v /= 255
            return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
        return 0.2126 * f(c[0]) + 0.7152 * f(c[1]) + 0.0722 * f(c[2])
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


# custom property -> colour, in the order the style sheet lists them.
CSS_TOKENS = [
    ('--nosum-parchment', PARCH),
    ('--nosum-parchment-deep', PARCH_LO),
    ('--nosum-parchment-light', PARCH_HI),
    ('--nosum-cream', draw.CREAM),
    ('--nosum-edge', WOOD_DD),
    ('--nosum-wood', WOOD),
    ('--nosum-wood-light', WOOD_L),
    ('--nosum-wood-dark', WOOD_D),
    ('--nosum-gold', GOLD),
    ('--nosum-gold-light', GOLD_L),
    ('--nosum-line', PARCH_DK),
    ('--nosum-ink', INK),
    ('--nosum-ink-soft', INK_SOFT),
    ('--nosum-ink-faint', INK_FAINT),
    ('--nosum-ink-on-dark', INK_ON_DARK),
    ('--nosum-heading', HEADING),
    ('--nosum-danger', DANGER),
    ('--nosum-ok', OK),
    ('--nosum-warn', WARN),
    ('--nosum-focus', FOCUS),
    ('--nosum-slot-bg', SLOT_FILL),
]

CSS_BEGIN = '    /* palette:begin (generated by tools/art_repack/palette.py; edit the palette there) */'
CSS_END = '    /* palette:end */'


def css_block():
    lines = [CSS_BEGIN]
    for name, c in CSS_TOKENS:
        lines.append('    %s: %s;' % (name, hexcolor(c)))
    lines.append('    --nosum-backdrop: %s;' % rgba(BACKDROP))
    lines.append('    --nosum-shine: %s;' % rgba(SHINE))
    lines.append(CSS_END)
    return '\n'.join(lines)


def apply_css(text):
    """text of nosum-theme.css with the generated block replaced (it must already hold the two markers)."""
    start = text.index(CSS_BEGIN)
    end = text.index(CSS_END) + len(CSS_END)
    return text[:start] + css_block() + text[end:]


def check_contrast():
    """The text colours reach 4.5 : 1 on both parchment steps; returns the failing pairs."""
    bad = []
    for text in (INK, INK_SOFT, INK_FAINT, HEADING, DANGER, OK):
        for page in (PARCH, PARCH_LO):
            if contrast(text, page) < 4.5:
                bad.append((text, page, contrast(text, page)))
    return bad
